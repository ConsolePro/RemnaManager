"""Build a self-contained POSIX .sh distribution from the reviewed local sources."""
import base64
import hashlib
import io
import pathlib
import tarfile
import textwrap

ROOT = pathlib.Path(__file__).resolve().parent
FILES = ['remnamanager.py', 'agent.py', 'lib/__init__.py', 'lib/runtime.py',
         'lib/render.py', 'lib/provision.py', 'lib/ssh.py', 'README.md']


def build():
    payload = io.BytesIO()
    with tarfile.open(fileobj=payload, mode='w:gz') as bundle:
        for name in FILES:
            content = (ROOT / name).read_bytes()
            member = tarfile.TarInfo(name)
            member.mode = 0o600
            member.size = len(content)
            member.mtime = 0
            bundle.addfile(member, io.BytesIO(content))
    content = payload.getvalue()
    digest = hashlib.sha256(content).hexdigest()
    encoded = '\n'.join(textwrap.wrap(base64.b64encode(content).decode(), width=76))
    script = f'''#!/bin/sh
# Generated by build.py. Source: remnamanager.py and lib/. Do not edit payload.
set -eu
[ "$(id -u)" -eq 0 ] || {{ echo 'Запустите от root: sudo sh remnamanager.sh' >&2; exit 1; }}
[ "$(uname -s)" = Linux ] || {{ echo 'Нужен Linux.' >&2; exit 1; }}
umask 077
if ! command -v python3 >/dev/null 2>&1; then
    apt-get update
    apt-get install -y python3
fi
python3 -c '
import base64, hashlib, io, os, pathlib, sys, tarfile, fcntl
payload = base64.b64decode(sys.stdin.read())
if hashlib.sha256(payload).hexdigest() != "{digest}":
    sys.exit("Повреждён архив RemnaManager")
root = pathlib.Path("/opt/remnamanager")
root.mkdir(parents=True, exist_ok=True, mode=0o700)
lock = (root / "manager.lock").open("w")
try:
    fcntl.flock(lock, fcntl.LOCK_EX | fcntl.LOCK_NB)
except BlockingIOError:
    sys.exit("Другой экземпляр RemnaManager уже работает")
destination = root / "app"
destination.mkdir(exist_ok=True, mode=0o700)
with tarfile.open(fileobj=io.BytesIO(payload), mode="r:gz") as archive:
    for member in archive.getmembers():
        relative = pathlib.PurePosixPath(member.name)
        if not member.isfile() or relative.is_absolute() or ".." in relative.parts:
            sys.exit("Недопустимый путь в архиве")
        target = destination.joinpath(*relative.parts)
        if not target.resolve().is_relative_to(destination.resolve()):
            sys.exit("Путь за пределами приложения")
        target.parent.mkdir(parents=True, exist_ok=True, mode=0o700)
        temporary = target.with_suffix(target.suffix + ".new")
        if temporary.is_symlink():
            sys.exit("Недопустимая ссылка")
        temporary.write_bytes(archive.extractfile(member).read())
        temporary.chmod(0o600)
        temporary.replace(target)
' <<'REMNAMANAGER_PAYLOAD'
{encoded}
REMNAMANAGER_PAYLOAD
exec python3 /opt/remnamanager/app/remnamanager.py "$@"
'''
    directory = ROOT / 'dist'
    directory.mkdir(exist_ok=True)
    target = directory / 'remnamanager.sh'
    target.write_text(script, encoding='utf-8', newline='\n')
    print(f'{target}: {len(script.encode())} bytes, payload SHA256 {digest}')


if __name__ == '__main__':
    build()
